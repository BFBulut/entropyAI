# Model 1: Fernholz (2002) Stochastic Portfolio Theory & Functionally Generated Portfolios
# ==============================================================================
class FernholzStochasticPortfolioEngine:
    """
    E. Robert Fernholz (2002) & Ioannis Karatzas: Stochastic Portfolio Theory (SPT)
    Implements Functionally Generated Portfolios (FGP) via market weight generating functions.
    Computes portfolio weights, excess growth rate (drift process dGamma_t), and volatility harvesting.
    """

    def __init__(self, p: float = 0.5):
        """
        p: diversity parameter for D_p(mu) = (sum mu_i^p)^(1/p), p in (0, 1).
        When p < 1, the portfolio systematically harvests market volatility without drift forecasting.
        """
        if not (0.0 < p < 1.0):
            raise ValueError("Diversity parameter p must be in (0, 1).")
        self.p = p

    def compute_diversity_weights(self, market_weights: np.ndarray) -> np.ndarray:
        """
        Given market capitalization weights mu in Delta^N,
        computes the functionally generated portfolio weights pi(t):
        pi_i(t) = mu_i(t)^p / sum_j mu_j(t)^p
        """
        mu = np.asarray(market_weights, dtype=float)
        if np.any(mu <= 0.0):
            raise ValueError("Market weights must be strictly positive.")
        mu_norm = mu / np.sum(mu)
        mu_pow = np.power(mu_norm, self.p)
        pi = mu_pow / np.sum(mu_pow)
        return pi

    def compute_entropy_weights(self, market_weights: np.ndarray) -> np.ndarray:
        """
        Portfolio generated by the Shannon entropy function:
        Phi(mu) = - sum mu_i ln(mu_i).
        pi_i = (1 - ln(mu_i) + sum_j mu_j ln(mu_j)) * mu_i / Phi(mu)
        """
        mu = np.asarray(market_weights, dtype=float)
        mu_norm = mu / np.sum(mu)
        entropy = -np.sum(mu_norm * np.log(mu_norm))
        if entropy <= 1e-12:
            return np.ones_like(mu_norm) / len(mu_norm)
        term = 1.0 - np.log(mu_norm) - entropy
        pi = (term * mu_norm) / entropy
        # Ensure projection to simplex
        pi = np.maximum(0.0, pi)
        return pi / np.sum(pi)

    def compute_volatility_harvesting_drift(
        self,
        market_weights: np.ndarray,
        covariance_matrix: np.ndarray
    ) -> Dict[str, float]:
        """
        Computes the instantaneous excess growth rate gamma*(t) of the diversity portfolio:
        gamma*(t) = (1 - p)/2 * [ sum_i pi_i sigma_ii - sum_{i,j} pi_i pi_j sigma_ij ]
        This drift represents guaranteed alpha harvested from market volatility.
        """
        mu = np.asarray(market_weights, dtype=float)
        pi = self.compute_diversity_weights(mu)
        cov = np.asarray(covariance_matrix, dtype=float)

        # Portfolio variance
        port_var = float(pi.T @ cov @ pi)
        # Weighted individual variances
        weighted_var = float(np.sum(pi * np.diag(cov)))
        # Excess growth rate
        excess_growth = (1.0 - self.p) * 0.5 * (weighted_var - port_var)

        # Entropy of market distribution
        mu_norm = mu / np.sum(mu)
        market_entropy = float(-np.sum(mu_norm * np.log(mu_norm)))

        return {
            "excess_growth_rate": excess_growth,
            "portfolio_variance": port_var,
            "weighted_variance": weighted_var,
            "market_entropy": market_entropy,
            "diversity_index": float(np.power(np.sum(np.power(mu_norm, self.p)), 1.0 / self.p))
        }

    def simulate_path_returns(
        self,
        initial_weights: np.ndarray,
        asset_returns: np.ndarray
    ) -> Dict[str, np.ndarray]:
        """
        Simulates multi-period dynamic rebalancing of FGP vs Market Buy-and-Hold.
        asset_returns: T x N array of asset simple returns.
        """
        T, N = asset_returns.shape
        mu_t = np.asarray(initial_weights, dtype=float)
        mu_t = mu_t / np.sum(mu_t)

        fgp_wealth = np.zeros(T + 1)
        market_wealth = np.zeros(T + 1)
        fgp_wealth[0] = 1.0
        market_wealth[0] = 1.0

        for t in range(T):
            r_t = asset_returns[t]
            pi_t = self.compute_diversity_weights(mu_t)

            # Portfolio returns
            r_fgp = np.sum(pi_t * r_t)
            r_mkt = np.sum(mu_t * r_t)

            fgp_wealth[t + 1] = fgp_wealth[t] * (1.0 + r_fgp)
            market_wealth[t + 1] = market_wealth[t] * (1.0 + r_mkt)

            # Update market weights with return dynamics
            new_val = mu_t * (1.0 + r_t)
            mu_t = new_val / np.sum(new_val)

        return {
            "fgp_wealth": fgp_wealth,
            "market_wealth": market_wealth,
            "relative_wealth": fgp_wealth / market_wealth
        }


