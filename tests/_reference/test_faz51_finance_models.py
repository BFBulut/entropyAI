# Model 2: Diebold & Yilmaz (2009, 2012) Financial Network Connectedness & GFEVD
# ==============================================================================
class DieboldYilmazConnectednessEngine:
    """
    Francis X. Diebold & Kamil Yilmaz (2009, 2012, 2014): Financial Network Connectedness
    Generalized Forecast Error Variance Decomposition (GFEVD) via Pesaran-Shin GVAR.
    Calculates Total Connectedness Index (TCI), Directional TO/FROM Spillovers, and Net Connectedness.
    """

    def __init__(self, n_vars: int):
        self.n_vars = n_vars

    def compute_gfevd(
        self,
        var_coefficients: List[np.ndarray],
        residual_covariance: np.ndarray,
        horizon: int = 10
    ) -> np.ndarray:
        """
        Computes the N x N GFEVD matrix Theta^g(H) where Theta_{ij} is the share of
        forecast error variance of variable i resulting from shocks to variable j.
        """
        N = self.n_vars
        p = len(var_coefficients)
        Sigma = np.asarray(residual_covariance, dtype=float)
        sigma_diag = np.diag(Sigma)

        # 1. Compute VMA coefficients A_h for h = 0, ..., H-1
        # A_0 = I_N, A_h = sum_{k=1}^{min(h, p)} A_{h-k} Phi_k
        A = [np.eye(N)]
        for h in range(1, horizon):
            Ah = np.zeros((N, N))
            for k in range(1, min(h, p) + 1):
                Ah += A[h - k] @ var_coefficients[k - 1]
            A.append(Ah)

        # 2. Generalized variance decomposition (Pesaran & Shin 1998)
        # Numerator: (1 / sigma_jj) * sum_{h=0}^{H-1} (e_i' A_h Sigma e_j)^2
        # Denominator: sum_{h=0}^{H-1} (e_i' A_h Sigma A_h' e_i)
        theta = np.zeros((N, N))
        for i in range(N):
            denom = 0.0
            for h in range(horizon):
                Ah = A[h]
                denom += Ah[i, :] @ Sigma @ Ah[i, :].T

            for j in range(N):
                numer = 0.0
                for h in range(horizon):
                    Ah = A[h]
                    term = Ah[i, :] @ Sigma[:, j]
                    numer += term * term
                theta[i, j] = (numer / sigma_diag[j]) / max(1e-12, denom)

        # 3. Row-wise normalization so sum_j theta_tilde_{ij} = 1.0
        row_sums = theta.sum(axis=1, keepdims=True)
        theta_norm = theta / np.maximum(1e-12, row_sums)
        return theta_norm

    def compute_connectedness_metrics(self, theta_norm: np.ndarray) -> Dict[str, Any]:
        """
        Extracts Total Connectedness Index (TCI), Directional TO/FROM spillovers,
        and Net Connectedness from the normalized GFEVD table.
        """
        N = theta_norm.shape[0]
        # Own shares: diagonal elements
        own_shares = np.diag(theta_norm)

        # Directional FROM others: sum_{j != i} theta_norm[i, j]
        from_others = np.sum(theta_norm, axis=1) - own_shares

        # Directional TO others: sum_{i != j} theta_norm[i, j]
        to_others = np.sum(theta_norm, axis=0) - own_shares

        # Net connectedness: TO - FROM
        net_connectedness = to_others - from_others

        # Total Connectedness Index (TCI): (sum_{i != j} theta_norm[i, j]) / N * 100
        total_spillover = np.sum(from_others)
        tci = (total_spillover / N) * 100.0

        return {
            "theta_matrix": theta_norm,
            "own_shares": own_shares,
            "from_others": from_others,
            "to_others": to_others,
            "net_connectedness": net_connectedness,
            "total_connectedness_index": float(tci),
            "net_transmitters": [int(i) for i in np.where(net_connectedness > 0)[0]],
            "net_receivers": [int(i) for i in np.where(net_connectedness < 0)[0]]
        }


