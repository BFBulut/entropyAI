# Model 5: Bruno Dupire (1994) Local Volatility Surface Stripping
# ==============================================================================
class DupireLocalVolatilityEngine:
    """
    Bruno Dupire (1993, 1994) & Emanuel Derman & Iraj Kani (1994):
    Local Volatility Surface Stripping & Calibration Engine.
    Computes local variance sigma_loc^2(K, T) directly from option call prices or implied variance w(y, T).
    Guarantees no division by zero and preserves non-negativity.
    """

    def __init__(self, r: float = 0.03, q: float = 0.0):
        self.r = r
        self.q = q

    def local_volatility_from_prices(
        self,
        S0: float,
        K: float,
        T: float,
        call_surface_fn,
        dK: float = 0.5,
        dT: float = 0.005
    ) -> float:
        """
        Dupire's original continuous-time PDE formula:
        sigma_loc^2(K, T) = [ dC/dT + q*C + (r - q)*K*dC/dK ] / [ 0.5 * K^2 * d^2C/dK^2 ]
        """
        if T <= 1e-4:
            return 0.2

        C = call_surface_fn(S0, K, T)
        C_T_plus = call_surface_fn(S0, K, T + dT)
        C_K_plus = call_surface_fn(S0, K + dK, T)
        C_K_minus = call_surface_fn(S0, K - dK, T)

        # Finite difference derivatives
        dC_dT = (C_T_plus - C) / dT
        dC_dK = (C_K_plus - C_K_minus) / (2.0 * dK)
        d2C_dK2 = (C_K_plus - 2.0 * C + C_K_minus) / (dK * dK)

        numerator = dC_dT + self.q * C + (self.r - self.q) * K * dC_dK
        denominator = 0.5 * (K * K) * d2C_dK2

        if denominator <= 1e-8 or numerator <= 0.0:
            # Fallback to local floor
            return 0.15

        loc_var = numerator / denominator
        return math.sqrt(max(0.01, min(4.0, loc_var)))

    def local_variance_from_implied_surface(
        self,
        y: float,
        T: float,
        w: float,
        dw_dT: float,
        dw_dy: float,
        d2w_dy2: float
    ) -> float:
        """
        Gatheral representation of Dupire local variance in log-moneyness y = ln(K / F):
        sigma_loc^2(y, T) = (dw/dT) / [ 1 - (y/w)*dw/dy + 0.25*(-0.25 - 1/w + y^2/w^2)*(dw/dy)^2 + 0.5*d2w/dy2 ]
        """
        if w <= 1e-8:
            return 0.04

        term1 = 1.0 - (y / w) * dw_dy
        term2 = 0.25 * (-0.25 - (1.0 / w) + (y * y) / (w * w)) * (dw_dy ** 2)
        term3 = 0.5 * d2w_dy2
        denom = term1 + term2 + term3

        if denom <= 1e-6 or dw_dT <= 0.0:
            return 0.04

        loc_var = dw_dT / denom
        return float(max(0.0001, min(4.0, loc_var)))


