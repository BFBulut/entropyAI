# Model 6: Gerber-Shiu (1998) Deficit at Ruin & Stopping Time Penalty Function
# ==============================================================================
class GerberShiuRuinPenaltyEngine:
    """
    Hans Gerber & Elias S.W. Shiu (1998): Deficit at Ruin & Actuarial-Financial Stopping Time Dynamics
    Calculates the expected discounted penalty function Phi(u) for compound Poisson surplus processes:
    U(t) = u + c*t - sum_{i=1}^{N(t)} X_i.
    Unifies probability of ultimate ruin, Laplace transform of ruin time, and expected deficit at ruin.
    """

    def __init__(self, premium_rate: float, claim_intensity: float, claim_scale: float):
        """
        c: premium rate
        lambda_c: Poisson claim arrival intensity
        beta_c: exponential claim parameter f(x) = beta_c * exp(-beta_c * x), mean claim = 1/beta_c.
        Net profit condition: c > lambda_c / beta_c.
        """
        if premium_rate <= claim_intensity / claim_scale:
            raise ValueError("Net profit condition violated: c must be > lambda / beta.")

        self.c = premium_rate
        self.lambda_c = claim_intensity
        self.beta = claim_scale

    def ruin_probability(self, u: float) -> float:
        """
        Classical Lundberg ultimate ruin probability (delta = 0, penalty w = 1):
        psi(u) = (lambda / (c * beta)) * exp( - (beta - lambda/c) * u )
        """
        if u < 0.0:
            return 1.0
        safety_loading = (self.c * self.beta) / self.lambda_c - 1.0
        decay_factor = self.beta - (self.lambda_c / self.c)
        prob = (1.0 / (1.0 + safety_loading)) * math.exp(-decay_factor * u)
        return float(max(0.0, min(1.0, prob)))

    def discounted_ruin_laplace_transform(self, u: float, delta: float) -> float:
        """
        Gerber-Shiu penalty function with penalty w = 1 and discount rate delta > 0.
        E[exp(-delta * tau) * I(tau < infty) | U(0) = u] = K * exp(-rho * u).
        Characteristic equation: c * r^2 + (c * beta - delta - lambda) * r - delta * beta = 0.
        Decay rate rho = (B + sqrt(B^2 + 4 * c * delta * beta)) / (2 * c) > 0.
        Boundary constant K = lambda / (c * rho + lambda + delta).
        """
        if u < 0.0:
            return 1.0
        B = self.c * self.beta - (delta + self.lambda_c)
        disc = B * B + 4.0 * self.c * delta * self.beta
        rho = (B + math.sqrt(disc)) / (2.0 * self.c)
        K = self.lambda_c / (self.c * rho + self.lambda_c + delta)
        laplace_val = K * math.exp(-rho * u)
        return float(max(0.0, min(1.0, laplace_val)))

    def expected_deficit_at_ruin(self, u: float) -> Dict[str, float]:
        """
        Expected deficit at ruin |U(tau)| given that ruin occurs:
        For memoryless exponential claims, the deficit |U(tau)| is exponentially distributed
        with parameter beta, independent of initial surplus u!
        E[|U(tau)| | tau < infty] = 1 / beta.
        Unconditional expected deficit = E[|U(tau)| * I(tau < infty)] = psi(u) * (1 / beta).
        """
        psi_u = self.ruin_probability(u)
        conditional_mean_deficit = 1.0 / self.beta
        unconditional_expected_deficit = psi_u * conditional_mean_deficit
        return {
            "initial_surplus": u,
            "ruin_probability": psi_u,
            "conditional_mean_deficit": conditional_mean_deficit,
            "unconditional_expected_deficit": unconditional_expected_deficit
        }


