# Model 3: Gatheral & Jacquier (2014) Arbitrage-Free SVI Volatility Surface
# ==============================================================================
class GatheralArbitrageFreeSVIEngine:
    """
    Jim Gatheral & Antoine Jacquier (2014): Arbitrage-Free SVI Implied Volatility Surface
    Raw SVI formulation: w(k) = a + b * [ rho*(k - m) + sqrt((k - m)^2 + sigma^2) ]
    Validates Roger Lee (2004) wing bounds and Durrleman (2002) density non-negativity (absence of butterfly arbitrage).
    """

    def __init__(self, a: float, b: float, rho: float, m: float, sigma: float):
        """
        Parameters of raw SVI:
        a in R, b >= 0, |rho| < 1, m in R, sigma > 0.
        """
        if b < 0.0:
            raise ValueError("b must be non-negative.")
        if abs(rho) >= 1.0:
            raise ValueError("|rho| must be strictly less than 1.")
        if sigma <= 0.0:
            raise ValueError("sigma must be strictly positive.")

        self.a = a
        self.b = b
        self.rho = rho
        self.m = m
        self.sigma = sigma

    def total_variance(self, k: float) -> float:
        """Total implied variance w(k) = sigma_impl^2 * T at log-moneyness k = ln(K/F)."""
        km = k - self.m
        return self.a + self.b * (self.rho * km + math.sqrt(km * km + self.sigma * self.sigma))

    def first_derivative(self, k: float) -> float:
        """w'(k) = b * [ rho + (k - m)/sqrt((k - m)^2 + sigma^2) ]."""
        km = k - self.m
        return self.b * (self.rho + km / math.sqrt(km * km + self.sigma * self.sigma))

    def second_derivative(self, k: float) -> float:
        """w''(k) = b * sigma^2 / ((k - m)^2 + sigma^2)^(3/2)."""
        km = k - self.m
        denom = (km * km + self.sigma * self.sigma) ** 1.5
        return self.b * (self.sigma * self.sigma) / denom

    def check_roger_lee_bounds(self) -> Dict[str, Any]:
        """
        Roger Lee (2004) Moment Formula requires:
        b * (1 + |rho|) < 2 to eliminate extreme strike arbitrage.
        """
        asymptotic_slope = self.b * (1.0 + abs(self.rho))
        is_valid = asymptotic_slope < 2.0
        return {
            "asymptotic_slope": asymptotic_slope,
            "roger_lee_threshold": 2.0,
            "is_valid": is_valid
        }

    def durrleman_density_factor(self, k: float) -> float:
        """
        Durrleman (2002) / Gatheral (2014) density non-negativity condition g(k) >= 0:
        g(k) = (1 - k*w'(k)/(2*w(k)))^2 - (w'(k)^2 / 4)*(1/w(k) + 1/4) + w''(k)/2
        """
        w = self.total_variance(k)
        if w <= 1e-12:
            return -1.0
        wp = self.first_derivative(k)
        wpp = self.second_derivative(k)

        term1 = (1.0 - (k * wp) / (2.0 * w)) ** 2
        term2 = (wp * wp / 4.0) * (1.0 / w + 0.25)
        term3 = 0.5 * wpp
        return term1 - term2 + term3

    def audit_butterfly_arbitrage(self, k_grid: np.ndarray) -> Dict[str, Any]:
        """
        Audits a range of strikes for static butterfly arbitrage (g(k) >= 0 everywhere).
        """
        g_vals = np.array([self.durrleman_density_factor(k) for k in k_grid])
        min_g = float(np.min(g_vals))
        has_arbitrage = min_g < 0.0
        return {
            "min_density_factor": min_g,
            "is_arbitrage_free": not has_arbitrage,
            "violations_count": int(np.sum(g_vals < 0.0))
        }

    def implied_volatility(self, k: float, T: float) -> float:
        """Implied volatility sigma(k, T) = sqrt(w(k) / T)."""
        if T <= 1e-8:
            return 0.0
        w = self.total_variance(k)
        return math.sqrt(max(0.0, w) / T)


