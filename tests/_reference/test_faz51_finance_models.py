# Model 4: Duffie, Filipovic & Schachermayer (2003) Affine Jump-Diffusion (AJD)
# ==============================================================================
class DuffieAffineJumpDiffusionEngine:
    """
    Darrell Duffie, Damir Filipović & Walter Schachermayer (2003) & Claudio Albanese & David Li (1998):
    Affine Jump-Diffusion (AJD) state-space solver.
    Solves complex matrix Riccati ODEs for characteristic functions and prices options via Gil-Pelaez inversion.
    Includes mean-reverting variance and compound Poisson jump dynamics.
    """

    def __init__(
        self,
        kappa: float,
        theta: float,
        sigma_v: float,
        rho: float,
        r: float,
        jump_intensity: float = 0.0,
        jump_mean: float = 0.0,
        jump_std: float = 0.0
    ):
        self.kappa = kappa
        self.theta = theta
        self.sigma_v = sigma_v
        self.rho = rho
        self.r = r
        self.lambda_j = jump_intensity
        self.mu_j = jump_mean
        self.sigma_j = jump_std

    def characteristic_function(self, u: complex, S0: float, V0: float, T: float) -> complex:
        """
        Analytical transform phi(u) = E[exp(i * u * ln(S_T)) | S_0, V_0].
        Solves Riccati ODEs C(tau, u) and D(tau, u).
        """
        # Intermediate terms
        i_u = 1j * u
        d = cmath.sqrt(
            (self.rho * self.sigma_v * i_u - self.kappa) ** 2
            - self.sigma_v ** 2 * (-i_u - u * u)
        )
        g = (self.kappa - self.rho * self.sigma_v * i_u - d) / (
            self.kappa - self.rho * self.sigma_v * i_u + d
        )

        exp_dt = cmath.exp(-d * T)
        # Riccati D(tau)
        D = (
            (self.kappa - self.rho * self.sigma_v * i_u - d)
            / (self.sigma_v ** 2)
            * ((1.0 - exp_dt) / (1.0 - g * exp_dt))
        )

        # Riccati C(tau) without jumps
        C = (
            i_u * math.log(S0)
            + i_u * self.r * T
            + (self.kappa * self.theta / (self.sigma_v ** 2))
            * (
                (self.kappa - self.rho * self.sigma_v * i_u - d) * T
                - 2.0 * cmath.log((1.0 - g * exp_dt) / (1.0 - g))
            )
        )

        # Jump adjustment (Merton / Kou affine jump component)
        if self.lambda_j > 0.0 and self.sigma_j > 0.0:
            jump_mgf = cmath.exp(i_u * self.mu_j + 0.5 * (i_u ** 2) * (self.sigma_j ** 2))
            drift_comp = self.lambda_j * (
                cmath.exp(self.mu_j + 0.5 * (self.sigma_j ** 2)) - 1.0
            )
            C += self.lambda_j * T * (jump_mgf - 1.0) - i_u * drift_comp * T

        return cmath.exp(C + D * V0)

    def price_european_call(
        self,
        S0: float,
        K: float,
        V0: float,
        T: float,
        n_points: int = 200,
        u_max: float = 50.0
    ) -> float:
        """
        Option pricing via Gil-Pelaez (1951) numerical integration of the characteristic function:
        Call = S0 * P1 - K * exp(-r*T) * P2
        """
        du = u_max / n_points
        u_grid = np.linspace(du * 0.5, u_max - du * 0.5, n_points)

        int1 = 0.0
        int2 = 0.0
        for u in u_grid:
            # P2 integrand: Re[ exp(-i*u*ln(K)) * phi(u) / (i*u) ]
            phi_u = self.characteristic_function(u, S0, V0, T)
            int2 += (cmath.exp(-1j * u * math.log(K)) * phi_u / (1j * u)).real * du

            # P1 integrand: Re[ exp(-i*u*ln(K)) * phi(u - i) / (i*u * S0 * exp(r*T)) ]
            phi_u_minus_i = self.characteristic_function(u - 1j, S0, V0, T)
            denom = 1j * u * S0 * math.exp(self.r * T)
            int1 += (cmath.exp(-1j * u * math.log(K)) * phi_u_minus_i / denom).real * du

        P1 = 0.5 + (1.0 / math.pi) * int1
        P2 = 0.5 + (1.0 / math.pi) * int2

        call_price = S0 * P1 - K * math.exp(-self.r * T) * P2
        return float(max(0.0, max(S0 - K * math.exp(-self.r * T), call_price)))


